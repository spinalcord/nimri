macro collectFrontendBinding*(target: typed; modulePath, nimName,
    wireName: static[string]; commandKind: static[FrontendCommandKind]): untyped =
  let definition = target.getImpl
  if definition.kind != nnkProcDef:
    error("frontend binding metadata requires a procedure", target)

  let formalParams = definition[3]
  var
    binding = FrontendBinding(
      commandKind: commandKind,
      modulePath: modulePath,
      nimName: nimName,
      tsName: lowerCamelCase(nimName),
      wireName: wireName
    )
    tsParameterNames = initHashSet[string]()

  for index in 1 ..< formalParams.len:
    let parameter = formalParams[index]
    if parameter.kind != nnkIdentDefs:
      error("unsupported frontend command parameter", parameter)
    for nameIndex in 0 ..< parameter.len - 2:
      let
        originalName = parameter[nameIndex].strVal
        tsName = lowerCamelCase(originalName)
      if tsName in tsParameterNames:
        error("frontend parameter name collision after lowerCamelCase: '" &
          tsName & "'", parameter[nameIndex])
      tsParameterNames.incl(tsName)
      binding.parameters.add(BindingParameter(
        nimName: originalName,
        tsName: tsName,
        parameterType: frontendType(parameter[^2]),
        hasDefault: parameter[^1].kind != nnkEmpty
      ))

  let
    futureType = futureValueType(formalParams[0])
    streamType = futureStreamValueType(formalParams[0])
  binding.returnType = frontendType(
    case commandKind
    of fckSynchronous: formalParams[0]
    of fckAsynchronous: futureType
    of fckStreaming: streamType
  )

  for existing in collectedBindings:
    if existing.modulePath == binding.modulePath and
        existing.tsName == binding.tsName:
      error("frontend command name collision after lowerCamelCase in module '" &
        binding.modulePath & "': '" & binding.tsName & "'", target)
    if existing.wireName == binding.wireName:
      error("duplicate frontend wire name '" & binding.wireName & "'", target)

  collectedBindings.add(binding)
  result = newEmptyNode()

macro createFrontendCommandAdapter(target: typed; modulePath, nimName,
    wireName: static[string]): untyped =
  let
    definition = target.getImpl
    formalParams = definition[3]
    futureType = futureValueType(formalParams[0])
    streamType = futureStreamValueType(formalParams[0])
    commandKind =
      if streamType.kind != nnkEmpty: fckStreaming
      elif futureType.kind != nnkEmpty: fckAsynchronous
      else: fckSynchronous
    argsNode = genSym(nskParam, "args")

  if futureType.kind != nnkEmpty and
      futureStreamValueType(futureType).kind != nnkEmpty:
    error("accessible commands cannot return Future[FutureStream[T]]; " &
      "return FutureStream[T] directly", formalParams[0])

  if commandKind == fckStreaming:
    if isVoidType(streamType):
      error("accessible streaming commands cannot return FutureStream[void]",
        formalParams[0])
    if futureValueType(streamType).kind != nnkEmpty or
        futureStreamValueType(streamType).kind != nnkEmpty:
      error("accessible streaming command elements cannot be Future or " &
        "FutureStream values", formalParams[0])

  var
    adapterBody = newStmtList()
    call = newCall(target)
    parameterValues = initOrderedTable[string, NimNode]()

  for index in 1 ..< formalParams.len:
    let parameter = formalParams[index]
    if parameter.kind != nnkIdentDefs:
      error("unsupported frontend command parameter", parameter)

    let parameterType = parameter[^2]
    if parameterType.kind == nnkEmpty:
      error("accessible command parameters need an explicit type", parameter)
    let parameterTypeDescriptor =
      newTree(nnkBracketExpr, bindSym"typedesc", parameterType)

    for nameIndex in 0 ..< parameter.len - 2:
      let
        parameterNode = parameter[nameIndex]
        parameterName = commandName(parameterNode)
        parameterNameLiteral = newLit(parameterName)
        localValue = genSym(nskLet, parameterName)

      if parameter[^1].kind == nnkEmpty:
        adapterBody.add quote do:
          if not `argsNode`.hasKey(`parameterNameLiteral`):
            raise newException(ValueError,
              "Missing required argument '" & `parameterNameLiteral` & "'")
          let `localValue` = frontendFromJson(
            `argsNode`[`parameterNameLiteral`], `parameterTypeDescriptor`)
      else:
        let defaultValue =
          defaultInAdapterContext(parameter[^1], parameterValues)
        adapterBody.add quote do:
          let `localValue`: `parameterType` =
            if `argsNode`.hasKey(`parameterNameLiteral`):
              frontendFromJson(
                `argsNode`[`parameterNameLiteral`],
                `parameterTypeDescriptor`)
            else:
              `defaultValue`

      call.add(localValue)
      parameterValues[parameterName] = localValue

  result = newStmtList()
  result.add newCall(bindSym"collectFrontendBinding", target,
    newLit(modulePath), newLit(nimName), newLit(wireName),
    newLit(commandKind))

  if commandKind == fckStreaming:
    let
      stream = genSym(nskLet, "stream")
      item = genSym(nskLet, "item")
    adapterBody.add quote do:
      let `stream` = `call`
      if `stream`.isNil:
        raise newException(
          ValueError, "Accessible streaming command returned a nil stream")
      result = FrontendStream(
        readNext: proc(): Future[FrontendStreamRead] {.async.} =
          let `item` = await `stream`.read()
          if `item`[0]:
            result = FrontendStreamRead(
              hasValue: true,
              value: frontendToJson(`item`[1])
            ),
        cancel: proc() =
          if not `stream`.failed:
            `stream`.complete()
      )

    result.add quote do:
      registerFrontendStreamCommand(
        `wireName`,
        proc(`argsNode`: JsonNode): FrontendStream =
          `adapterBody`
      )
  elif commandKind == fckAsynchronous:
    if futureType.kind == nnkEmpty:
      error("internal error resolving asynchronous frontend result", target)
    elif isVoidType(futureType):
      adapterBody.add quote do:
        await `call`
        result = newJNull()
    else:
      let value = genSym(nskLet, "value")
      adapterBody.add quote do:
        let `value` = await `call`
        result = frontendToJson(`value`)

    result.add quote do:
      registerFrontendAsyncCommand(
        `wireName`,
        proc(`argsNode`: JsonNode): Future[JsonNode] {.async.} =
          `adapterBody`
      )
  else:
    if formalParams[0].kind == nnkEmpty:
      adapterBody.add(call)
      adapterBody.add quote do:
        result = newJNull()
    else:
      adapterBody.add quote do:
        result = frontendToJson(`call`)

    result.add quote do:
      registerFrontendSyncCommand(
        `wireName`,
        proc(`argsNode`: JsonNode): JsonNode =
          `adapterBody`
      )

macro accessible*(definition: untyped): untyped =
  ## Exposes a typed procedure through the frontend command registry and
  ## records its resolved signature for TypeScript generation.
  if definition.kind != nnkProcDef:
    error("accessible can only be applied to a procedure", definition)

  let genericParams = definition[2]
  if genericParams.kind != nnkEmpty and genericParams.len > 0:
    error("accessible commands cannot be generic", genericParams)

  let
    nimName = commandName(definition[0])
    target = callableName(definition[0])
    modulePath = modulePathFor(definition.lineInfoObj.filename)
    wireName = modulePath.replace('/', '.') & "." & nimName
  result = newStmtList(definition)
  result.add newCall(bindSym"createFrontendCommandAdapter", target,
    newLit(modulePath), newLit(nimName), newLit(wireName))

