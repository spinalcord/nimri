proc commandName(node: NimNode): string {.compileTime.} =
  case node.kind
  of nnkIdent, nnkSym:
    result = node.strVal
  of nnkPostfix:
    result = commandName(node[1])
  else:
    error("frontend only supports normally named procedures", node)

proc callableName(node: NimNode): NimNode {.compileTime.} =
  case node.kind
  of nnkIdent, nnkSym:
    result = node.copyNimTree
  of nnkPostfix:
    result = node[1].copyNimTree
  else:
    error("frontend only supports normally named procedures", node)

proc defaultInAdapterContext(node: NimNode;
    parameterValues: OrderedTable[string, NimNode]): NimNode {.compileTime.} =
  ## Default expressions are copied out of the procedure declaration and into
  ## the generated adapter. Make earlier converted/defaulted parameters
  ## available under their source names, letting Nim resolve identifiers inside
  ## the expression exactly as it normally would (including field names and
  ## nested scopes).
  result = newNimNode(nnkStmtListExpr)
  for name, value in parameterValues:
    result.add(newLetStmt(newIdentNode(name), value.copyNimTree))

  proc copyWithAdapterParameters(current: NimNode): NimNode =
    if current.kind == nnkSym and parameterValues.hasKey(current.strVal):
      return newIdentNode(current.strVal)
    result = current.copyNimNode
    for child in current:
      result.add(copyWithAdapterParameters(child))

  result.add(copyWithAdapterParameters(node))

proc lowerCamelCase(name: string): string {.compileTime.} =
  var uppercaseNext = false
  for character in name:
    if character == '_':
      uppercaseNext = true
    elif result.len == 0:
      result.add(character.toLowerAscii())
      uppercaseNext = false
    elif uppercaseNext:
      result.add(character.toUpperAscii())
      uppercaseNext = false
    else:
      result.add(character)

  if result.len == 0:
    error("frontend names cannot consist only of underscores")

proc isExportedName(node: NimNode): bool {.compileTime.} =
  node.kind == nnkPostfix and node.len == 2 and node[0].strVal == "*"

proc modulePathFor(filename: string): string {.compileTime.} =
  let
    source = filename.normalizedPath
    portableSource = source.replace(DirSep, '/')
    featuresMarker = "/features/"
    featureIndex = portableSource.rfind(featuresMarker)

  if featureIndex >= 0:
    let
      featureStart = featureIndex + featuresMarker.len
      commandsMarker = "/commands/"
      commandsIndex = portableSource.find(commandsMarker, featureStart)
    if commandsIndex < 0:
      error("accessible feature commands must be declared below a commands " &
        "directory", newLit(filename))
    result = portableSource[featureStart ..< commandsIndex]
    if result.len == 0:
      error("accessible commands require a non-empty feature path",
        newLit(filename))
  else:
    result = source.extractFilename.changeFileExt("")

proc replaceTypeParameters(typeNode: NimNode;
    replacements: Table[string, NimNode]): NimNode {.compileTime.} =
  if typeNode.kind in {nnkIdent, nnkSym} and
      replacements.hasKey(typeNode.strVal):
    return replacements[typeNode.strVal].copyNimTree

  result = typeNode.copyNimNode
  for child in typeNode:
    result.add(replaceTypeParameters(child, replacements))

proc wrappedValueType(typeNode, wrapper: NimNode): NimNode {.compileTime.} =
  let node =
    if typeNode.kind == nnkVarTy: typeNode[0]
    else: typeNode

  if node.kind == nnkBracketExpr and node.len == 2 and
      (node[0].sameType(wrapper) or node[0].eqIdent(wrapper.strVal)):
    return node[1]

  if node.kind == nnkBracketExpr and node.len > 1 and
      node[0].kind == nnkSym:
    let definition = node[0].getImpl
    if definition.kind == nnkTypeDef and
        definition[1].kind == nnkGenericParams and
        definition[1].len == node.len - 1:
      var replacements = initTable[string, NimNode]()
      for index, parameter in definition[1]:
        if parameter.kind notin {nnkIdent, nnkSym}:
          return newEmptyNode()
        replacements[parameter.strVal] = node[index + 1]
      return wrappedValueType(
        replaceTypeParameters(definition[2], replacements), wrapper)

  if node.kind == nnkSym:
    let definition = node.getImpl
    if definition.kind == nnkTypeDef:
      return wrappedValueType(definition[2], wrapper)

  result = newEmptyNode()

proc futureValueType(typeNode: NimNode): NimNode {.compileTime.} =
  wrappedValueType(typeNode, bindSym"Future")

proc futureStreamValueType(typeNode: NimNode): NimNode {.compileTime.} =
  wrappedValueType(typeNode, bindSym"FutureStream")

proc isVoidType(typeNode: NimNode): bool {.compileTime.} =
  if typeNode.kind in {nnkIdent, nnkSym} and typeNode.eqIdent("void"):
    return true
  if typeNode.kind == nnkSym:
    let definition = typeNode.getImpl
    if definition.kind == nnkTypeDef:
      return isVoidType(definition[2])

